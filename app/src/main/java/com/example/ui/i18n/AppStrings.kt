fun appStringsFor(code: String): AppStrings = when (code.lowercase()) {
    "hi" -> hindiStrings()
    "ta" -> tamilStrings()
    "te" -> teluguStrings()
    "bn" -> bengaliStrings()
    "mr" -> marathiStrings()
    "gu" -> gujaratiStrings()
    "kn" -> kannadaStrings()
    "ml" -> malayalamStrings()
    "pa" -> punjabiStrings()
    "or" -> odiaStrings()
    "ur" -> urduStrings()
    "as" -> assameseStrings()
    "sa" -> sanskritStrings()
    "mai" -> maithiliStrings()
    else -> englishStrings()
}

